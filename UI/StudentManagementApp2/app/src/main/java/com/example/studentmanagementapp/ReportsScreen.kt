// CATEGORY LOGIC
// =====================================================

private fun getReportCategory(
    student: Student
): String {

    /*
     * Valid categories are controlled by AdmissionCatalog.
     *
     * EWS is intentionally NOT included here.
     */

    val allocated =
        student.allocatedCategory.trim()

    if (
        allocated.isNotBlank() &&
        AdmissionCatalog.categories.any {
            it.equals(
                allocated,
                ignoreCase = true
            )
        }
    ) {
        return canonicalCategory(allocated)
    }


    val eligible =
        student.eligibleCategory.trim()

    if (
        eligible.isNotBlank() &&
        AdmissionCatalog.categories.any {
            it.equals(
                eligible,
                ignoreCase = true
            )
        }
    ) {
        return canonicalCategory(eligible)
    }


    return "Other"
}


// =====================================================
// CATEGORY CANONICALIZATION
// =====================================================

private fun canonicalCategory(
    category: String
): String {

    return when (category.trim().lowercase()) {

        "ur" ->
            "UR"

        "obc" ->
            "OBC"

        "sc" ->
            "SC"

        "st" ->
            "ST"

        "other" ->
            "Other"

        else ->
            "Other"
    }
}


// =====================================================
// STATUS LOGIC
// =====================================================

private fun getReportStatus(
    student: Student
): String {

    val status =
        student.status.trim()

    AdmissionCatalog.admissionStatuses.forEach {
            validStatus ->

        if (
            validStatus.equals(
                status,
                ignoreCase = true
            )
        ) {
            return validStatus
        }
    }

    return "Not Specified"
}


// =====================================================
// EWS NORMALIZATION
// =====================================================

private fun normalizeEws(
    ews: String
): String {

    return when (
        ews.trim().lowercase()
    ) {

        "yes",
        "y",
        "true" ->
            "Yes"

        "no",
        "n",
        "false" ->
            "No"

        else ->
            "Not Specified"
    }
}


// =====================================================
// GENERAL VALUE NORMALIZATION
// =====================================================

private fun normalizeValue(
    value: String
): String {

    return value.trim()
        .takeIf {
            it.isNotBlank()
        }
        ?: "Not Specified"
}


// =====================================================
// GROUP STUDENTS
// =====================================================

private fun getStudentsForGroup(
    reportType: String,
    groupName: String,
    students: List<Student>
): List<Student> {

    return when (reportType) {

        "Student Report" ->
            students


        "Admission Report" ->
            students


        "Branch-wise Report" ->

            students.filter {

                BranchCatalog
                    .canonicalBranch(it.branch)
                    .ifBlank {
                        "Not Specified"
                    } == groupName
            }


        "Category-wise Report" ->

            students.filter {

                getReportCategory(it) == groupName
            }


        "Status-wise Report" ->

            students.filter {

                getReportStatus(it) == groupName
            }


        "EWS Summary" ->

            students.filter {

                normalizeEws(it.ews) == groupName
            }


        "Domicile Summary" ->

            students.filter {

                normalizeValue(it.domicile) == groupName
            }


        "Religion Summary" ->

            students.filter {

                normalizeValue(it.religion) == groupName
            }


        else ->
            emptyList()
    }
}

