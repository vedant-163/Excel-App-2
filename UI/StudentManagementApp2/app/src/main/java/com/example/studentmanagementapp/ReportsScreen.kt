private val ReportsBlue = Color(0xFF1565C0)
private val ReportsBackground = Color(0xFFF5F7FB)
private val ReportsDarkText = Color(0xFF172033)
private val ReportsLightBlue = Color(0xFFEAF2FF)
private val ReportsLightButton = Color(0xFFE9EEF5)

private const val ALL_YEARS = "All Years"
private const val ALL_BRANCHES = "All Branches"
private const val ALL_CATEGORIES = "All Categories"


// =====================================================
// REPORT SCREEN
// =====================================================

@Composable
fun ReportsScreen(
    students: SnapshotStateList<Student>,
    onBack: () -> Unit
) {

    var selectedYear by remember {
        mutableStateOf(ALL_YEARS)
    }

    var selectedBranch by remember {
        mutableStateOf(ALL_BRANCHES)
    }

    var selectedCategory by remember {
        mutableStateOf(ALL_CATEGORIES)
    }

    var selectedReportType by remember {
        mutableStateOf("Student Report")
    }

    var reportGenerated by remember {
        mutableStateOf(false)
    }

    var reportLoading by remember { mutableStateOf(false) }
    var reportError by remember { mutableStateOf<String?>(null) }
    var reportStudents by remember { mutableStateOf<List<Student>>(emptyList()) }
    val reportScope = rememberCoroutineScope()
    val context = androidx.compose.ui.platform.LocalContext.current

    /*
     * Drill-down state
     *
     * null = main reports screen
     * selectedGroup != null = group student list
     * selectedStudent != null = student details
     */
    var selectedGroup by remember {
        mutableStateOf<String?>(null)
    }

    var selectedStudent by remember {
        mutableStateOf<Student?>(null)
    }


    // =====================================================
    // CENTRAL CATALOG VALUES
    // =====================================================

    val academicYearOptions =
        listOf(ALL_YEARS) + AdmissionCatalog.academicYears

    val branchOptions = remember(selectedYear) {

        if (selectedYear == ALL_YEARS) {

            listOf(ALL_BRANCHES) +
                    (
                            BranchCatalog.standardBranches +
                                    BranchCatalog.AI_ROBOTICS
                            ).distinct()

        } else {

            val admissionYear =
                AdmissionCatalog.admissionYearForAcademicYear(
                    selectedYear
                )

            listOf(ALL_BRANCHES) +
                    BranchCatalog.optionsForAcademicYear(
                        admissionYear
                    ).distinct()
        }
    }

    val categoryOptions =
        listOf(ALL_CATEGORIES) +
                AdmissionCatalog.categories


    /*
     * If academic year changes and selected branch is no longer
     * available, automatically reset branch.
     */
    LaunchedEffect(branchOptions) {

        if (selectedBranch !in branchOptions) {
            selectedBranch = ALL_BRANCHES
        }
    }


    // =====================================================
    // FILTERED STUDENTS
    // =====================================================

    val sourceStudents = if (reportGenerated) reportStudents else emptyList()

    val filteredStudents = sourceStudents.filter { student ->

        matchesAcademicYear(
            student = student,
            selectedAcademicYear = selectedYear
        ) &&
                matchesBranch(
                    student = student,
                    selectedBranch = selectedBranch
                ) &&
                matchesCategory(
                    student = student,
                    selectedCategory = selectedCategory
                )
    }


    // =====================================================
    // STUDENT DETAILS
    // =====================================================

    if (selectedStudent != null) {

        ReportStudentDetailsScreen(
            student = selectedStudent!!,
            onBack = {
                selectedStudent = null
            }
        )

        return
    }


    // =====================================================
    // GROUP STUDENT LIST
    // =====================================================

    if (selectedGroup != null) {

        val groupStudents =
            getStudentsForGroup(
                reportType = selectedReportType,
                groupName = selectedGroup!!,
                students = filteredStudents
            )

        ReportGroupStudentsScreen(
            groupName = selectedGroup!!,
            reportType = selectedReportType,
            students = groupStudents,
            onBack = {
                selectedGroup = null
            },
            onStudentClick = {
                selectedStudent = it
            }
        )

        return
    }


    // =====================================================
    // MAIN REPORT SCREEN
    // =====================================================

    Surface(
        modifier = Modifier.fillMaxSize(),
        color = ReportsBackground
    ) {

        LazyColumn(
            modifier = Modifier.fillMaxSize()
        ) {

            // =================================================
            // HEADER
            // =================================================

            item {

                Card(
                    modifier = Modifier.fillMaxWidth(),
                    shape = RoundedCornerShape(
                        bottomStart = 24.dp,
                        bottomEnd = 24.dp
                    ),
                    colors = CardDefaults.cardColors(
                        containerColor = ReportsBlue
                    ),
                    elevation = CardDefaults.cardElevation(4.dp)
                ) {

                    Column(
                        modifier = Modifier.padding(
                            horizontal = 18.dp,
                            vertical = 20.dp
                        )
                    ) {

                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            verticalAlignment = Alignment.CenterVertically
                        ) {

                            Box(
                                modifier = Modifier
                                    .background(
                                        Color.White.copy(alpha = 0.15f),
                                        RoundedCornerShape(12.dp)
                                    )
                                    .clickable {
                                        onBack()
                                    }
                                    .padding(
                                        horizontal = 13.dp,
                                        vertical = 9.dp
                                    )
                            ) {

                                Text(
                                    text = "←",
                                    color = Color.White,
                                    fontSize = 23.sp,
                                    fontWeight = FontWeight.Bold
                                )
                            }

                            Spacer(
                                modifier = Modifier.width(14.dp)
                            )

                            Column(
                                modifier = Modifier.weight(1f)
                            ) {

                                Text(
                                    text = "Reports",
                                    color = Color.White,
                                    fontSize = 25.sp,
                                    fontWeight = FontWeight.Bold
                                )

                                Text(
                                    text = "View and analyse student records",
                                    color = Color.White.copy(alpha = 0.85f),
                                    fontSize = 13.sp
                                )
                            }
                        }
                    }
                }
            }


            item {
                Spacer(
                    modifier = Modifier.height(18.dp)
                )
            }


            // =================================================
            // RECORD SUMMARY
            // =================================================

            item {

                ReportsInfoCard(
                    totalStudents = students.size
                )
            }


            item {
                Spacer(
                    modifier = Modifier.height(18.dp)
                )
            }


            // =================================================
            // REPORT FILTER CARD
            // =================================================

            item {

                Card(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(horizontal = 16.dp),
                    shape = RoundedCornerShape(18.dp),
                    colors = CardDefaults.cardColors(
                        containerColor = Color.White
                    ),
                    elevation = CardDefaults.cardElevation(3.dp)
                ) {

                    Column(
                        modifier = Modifier.padding(18.dp)
                    ) {

                        Text(
                            text = "Generate Report",
                            fontSize = 19.sp,
                            fontWeight = FontWeight.Bold,
                            color = ReportsDarkText
                        )

                        Spacer(
                            modifier = Modifier.height(3.dp)
                        )

                        Text(
                            text = "Select report type and filters.",
                            fontSize = 12.sp,
                            color = Color.Gray
                        )


                        Spacer(
                            modifier = Modifier.height(18.dp)
                        )


                        // =============================================
                        // REPORT TYPE
                        // =============================================

                        ReportsFieldLabel("Report Type")

                        ReportsDropdown(
                            selected = selectedReportType,
                            options = listOf(
                                "Student Report",
                                "Admission Report",
                                "Branch-wise Report",
                                "Category-wise Report",
                                "Status-wise Report",
                                "EWS Summary",
                                "Domicile Summary",
                                "Religion Summary"
                            ),
                            label = "Select report type",
                            onSelected = {
                                selectedReportType = it
                                reportGenerated = false
                                selectedGroup = null
                            }
                        )


                        Spacer(
                            modifier = Modifier.height(12.dp)
                        )


                        // =============================================
                        // ACADEMIC YEAR
                        // =============================================

                        ReportsFieldLabel("Academic Year")

                        ReportsDropdown(
                            selected = selectedYear,
                            options = academicYearOptions,
                            label = "Academic Year",
                            onSelected = {
                                selectedYear = it
                                reportGenerated = false
                            }
                        )


                        Spacer(
                            modifier = Modifier.height(12.dp)
                        )


                        // =============================================
                        // BRANCH
                        // =============================================

                        ReportsFieldLabel("Course / Branch")

                        ReportsDropdown(
                            selected = selectedBranch,
                            options = branchOptions,
                            label = "Branch",
                            onSelected = {
                                selectedBranch = it
                                reportGenerated = false
                            }
                        )


                        Spacer(
                            modifier = Modifier.height(12.dp)
                        )


                        // =============================================
                        // CATEGORY
                        // =============================================

                        ReportsFieldLabel("Category")

                        ReportsDropdown(
                            selected = selectedCategory,
                            options = categoryOptions,
                            label = "Category",
                            onSelected = {
                                selectedCategory = it
                                reportGenerated = false
                            }
                        )


                        Spacer(
                            modifier = Modifier.height(18.dp)
                        )


                        // =============================================
                        // BUTTONS
                        // =============================================

                        Row(
                            modifier = Modifier.fillMaxWidth(),
                            horizontalArrangement = Arrangement.spacedBy(10.dp)
                        ) {

                            Button(
                                onClick = {
                                    reportLoading = true
                                    reportError = null
                                    selectedGroup = null
                                    selectedStudent = null
                                    reportScope.launch {
                                        try {
                                            val yearFilter = selectedYear.takeUnless { it == ALL_YEARS }
                                                ?.let { AdmissionCatalog.admissionYearForAcademicYear(it) }
                                            val branchFilter = selectedBranch.takeUnless { it == ALL_BRANCHES }
                                            val categoryFilter = selectedCategory.takeUnless { it == ALL_CATEGORIES }
                                            reportStudents = ApiClient.getReportStudents(
                                                context = context,
                                                admissionYear = yearFilter,
                                                branch = branchFilter,
                                                eligibleCategory = categoryFilter
                                            )
                                            reportGenerated = true
                                        } catch (e: Exception) {
                                            reportError = e.message ?: "Unable to load report data."
                                            reportGenerated = false
                                        } finally {
                                            reportLoading = false
                                        }
                                    }
                                },
                                modifier = Modifier.weight(1f),
                                shape = RoundedCornerShape(12.dp),
                                colors = ButtonDefaults.buttonColors(
                                    containerColor = ReportsBlue
                                )
                            ) {

                                if (reportLoading) {
                                    androidx.compose.material3.CircularProgressIndicator(
                                        modifier = Modifier.width(18.dp).height(18.dp),
                                        strokeWidth = 2.dp,
                                        color = Color.White
                                    )
                                } else {
                                    Text(
                                        text = "Generate",
                                        fontWeight = FontWeight.Bold
                                    )
                                }
                            }


                            Button(
                                onClick = {

                                    selectedYear = ALL_YEARS
                                    selectedBranch = ALL_BRANCHES
                                    selectedCategory = ALL_CATEGORIES

                                    selectedReportType =
                                        "Student Report"

                                    reportGenerated = false
                                    reportStudents = emptyList()
                                    reportError = null
                                    selectedGroup = null
                                    selectedStudent = null
                                },
                                modifier = Modifier.weight(1f),
                                shape = RoundedCornerShape(12.dp),
                                colors = ButtonDefaults.buttonColors(
                                    containerColor = ReportsLightButton,
                                    contentColor = Color(0xFF374151)
                                )
                            ) {

                                Text(
                                    text = "Clear",
                                    fontWeight = FontWeight.SemiBold
                                )
                            }
                        }
                    }
                }
            }


            item {
                Spacer(
                    modifier = Modifier.height(18.dp)
                )
            }


            if (reportError != null) {
                item {
                    Card(
                        modifier = Modifier.fillMaxWidth().padding(horizontal = 16.dp),
                        shape = RoundedCornerShape(16.dp),
                        colors = CardDefaults.cardColors(containerColor = Color.White)
                    ) {
                        Column(modifier = Modifier.padding(18.dp)) {
                            Text("Report loading failed", fontWeight = FontWeight.Bold, color = Color(0xFFB42318))
                            Spacer(modifier = Modifier.height(6.dp))
                            Text(reportError!!, fontSize = 13.sp, color = Color.Gray)
                        }
                    }
                }
                item { Spacer(modifier = Modifier.height(12.dp)) }
            }

            // =================================================
            // BEFORE GENERATING
            // =================================================

            if (!reportGenerated) {

                item {

                    ReportsEmptyState(
                        totalStudents = students.size
                    )
                }

            } else {

                // =================================================
                // FILTER SUMMARY
                // =================================================

                item {

                    ReportsActiveFilterCard(
                        reportType = selectedReportType,
                        academicYear = selectedYear,
                        branch = selectedBranch,
                        category = selectedCategory
                    )
                }


                item {
                    Spacer(
                        modifier = Modifier.height(18.dp)
                    )
                }


                // =================================================
                // SUMMARY
                // =================================================

                item {

                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(horizontal = 16.dp),
                        verticalAlignment = Alignment.CenterVertically
                    ) {

                        Text(
                            text = "Report Summary",
                            fontSize = 19.sp,
                            fontWeight = FontWeight.Bold,
                            color = ReportsDarkText,
                            modifier = Modifier.weight(1f)
                        )

                        Text(
                            text = "${filteredStudents.size} records",
                            fontSize = 13.sp,
                            color = ReportsBlue,
                            fontWeight = FontWeight.SemiBold
                        )
                    }
                }


                item {
                    Spacer(
                        modifier = Modifier.height(10.dp)
                    )
                }


                item {

                    ReportsSummaryCards(
                        students = filteredStudents
                    )
                }


                item {
                    Spacer(
                        modifier = Modifier.height(18.dp)
                    )
                }


                // =================================================
                // REPORT RESULTS
                // =================================================

                item {

                    Text(
                        text = selectedReportType,
                        fontSize = 19.sp,
                        fontWeight = FontWeight.Bold,
                        color = ReportsDarkText,
                        modifier = Modifier.padding(
                            horizontal = 16.dp
                        )
                    )
                }


                item {
                    Spacer(
                        modifier = Modifier.height(10.dp)
                    )
                }


                // =================================================
                // REPORT TYPE CONTENT
                // =================================================

                when (selectedReportType) {

                    "Student Report" -> {

                        item {

                            ReportGroupCard(
                                title = "All Students",
                                count = filteredStudents.size,
                                subtitle = "Click to view student records",
                                onClick = {

                                    if (filteredStudents.isNotEmpty()) {
                                        selectedGroup = "All Students"
                                    }
                                }
                            )
                        }
                    }


                    "Admission Report" -> {

                        item {

                            ReportGroupCard(
                                title = "All Admissions",
                                count = filteredStudents.size,
                                subtitle = "Click to view admission records",
                                onClick = {

                                    if (filteredStudents.isNotEmpty()) {
                                        selectedGroup = "All Admissions"
                                    }
                                }
                            )
                        }
                    }


                    "Branch-wise Report" -> {

                        val branchGroups =
                            filteredStudents
                                .groupBy {
                                    BranchCatalog
                                        .canonicalBranch(it.branch)
                                        .ifBlank {
                                            "Not Specified"
                                        }
                                }
                                .toSortedMap()

                        if (branchGroups.isEmpty()) {

                            item {

                                ReportsNoResultCard(
                                    text = "No branch records found."
                                )
                            }

                        } else {

                            branchGroups.forEach { (branch, list) ->

                                item {

                                    ReportGroupCard(
                                        title = branch,
                                        count = list.size,
                                        subtitle = "Click to view students",
                                        onClick = {
                                            selectedGroup = branch
                                        }
                                    )
                                }
                            }
                        }
                    }


                    "Category-wise Report" -> {

                        val categoryGroups =
                            filteredStudents
                                .groupBy {
                                    getReportCategory(it)
                                }
                                .toSortedMap()

                        if (categoryGroups.isEmpty()) {

                            item {

                                ReportsNoResultCard(
                                    text = "No category records found."
                                )
                            }

                        } else {

                            categoryGroups.forEach { (category, list) ->

                                item {

                                    ReportGroupCard(
                                        title = category,
                                        count = list.size,
                                        subtitle = "Click to view students",
                                        onClick = {
                                            selectedGroup = category
                                        }
                                    )
                                }
                            }
                        }
                    }


                    "Status-wise Report" -> {

                        val statusGroups =
                            filteredStudents
                                .groupBy {
                                    getReportStatus(it)
                                }
                                .toSortedMap()

                        if (statusGroups.isEmpty()) {

                            item {

                                ReportsNoResultCard(
                                    text = "No status records found."
                                )
                            }

                        } else {

                            statusGroups.forEach { (status, list) ->

                                item {

                                    ReportGroupCard(
                                        title = status,
                                        count = list.size,
                                        subtitle = "Click to view students",
                                        onClick = {
                                            selectedGroup = status
                                        }
                                    )
                                }
                            }
                        }
                    }


                    "EWS Summary" -> {

                        val ewsGroups =
                            filteredStudents
                                .groupBy {
                                    normalizeEws(it.ews)
                                }
                                .toSortedMap()

                        if (ewsGroups.isEmpty()) {

                            item {

                                ReportsNoResultCard(
                                    text = "No EWS records found."
                                )
                            }

                        } else {

                            ewsGroups.forEach { (ews, list) ->

                                item {

                                    ReportGroupCard(
                                        title = ews,
                                        count = list.size,
                                        subtitle = "Click to view students",
                                        onClick = {
                                            selectedGroup = ews
                                        }
                                    )
                                }
                            }
                        }
                    }


                    "Domicile Summary" -> {

                        val domicileGroups =
                            filteredStudents
                                .groupBy {
                                    normalizeValue(it.domicile)
                                }
                                .toSortedMap()

                        if (domicileGroups.isEmpty()) {

                            item {

                                ReportsNoResultCard(
                                    text = "No domicile records found."
                                )
                            }

                        } else {

                            domicileGroups.forEach { (domicile, list) ->

                                item {

                                    ReportGroupCard(
                                        title = domicile,
                                        count = list.size,
                                        subtitle = "Click to view students",
                                        onClick = {
                                            selectedGroup = domicile
                                        }
                                    )
                                }
                            }
                        }
                    }


                    "Religion Summary" -> {

                        val religionGroups =
                            filteredStudents
                                .groupBy {
                                    normalizeValue(it.religion)
                                }
                                .toSortedMap()

                        if (religionGroups.isEmpty()) {

                            item {

                                ReportsNoResultCard(
                                    text = "No religion records found."
                                )
                            }

                        } else {

                            religionGroups.forEach { (religion, list) ->

                                item {

                                    ReportGroupCard(
                                        title = religion,
                                        count = list.size,
                                        subtitle = "Click to view students",
                                        onClick = {
                                            selectedGroup = religion
                                        }
                                    )
                                }
                            }
                        }
                    }
                }
            }


            item {
                Spacer(
                    modifier = Modifier.height(25.dp)
                )
            }
        }
    }
}


