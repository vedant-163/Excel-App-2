// =====================================================
// DROPDOWN
// =====================================================

@Composable
private fun ReportsDropdown(
    selected: String,
    options: List<String>,
    label: String,
    onSelected: (String) -> Unit
) {

    var expanded by remember {
        mutableStateOf(false)
    }

    Box(
        modifier = Modifier.fillMaxWidth()
    ) {

        OutlinedTextField(
            value = selected,
            onValueChange = {},
            modifier = Modifier
                .fillMaxWidth()
                .clickable {
                    expanded = true
                },
            label = {
                Text(label)
            },
            readOnly = true,
            singleLine = true,
            shape = RoundedCornerShape(12.dp)
        )


        Box(
            modifier = Modifier
                .matchParentSize()
                .clickable {
                    expanded = true
                }
        )


        DropdownMenu(
            expanded = expanded,
            onDismissRequest = {
                expanded = false
            },
            modifier = Modifier.fillMaxWidth()
        ) {

            options.forEach { option ->

                DropdownMenuItem(
                    text = {
                        Text(option)
                    },
                    onClick = {

                        onSelected(option)
                        expanded = false
                    }
                )
            }
        }
    }
}


