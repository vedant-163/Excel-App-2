// =====================================================
// ACADEMIC YEAR FILTER
// =====================================================

private fun matchesAcademicYear(
    student: Student,
    selectedAcademicYear: String
): Boolean {

    if (selectedAcademicYear == ALL_YEARS) {
        return true
    }

    /*
     * IMPORTANT:
     *
     * We NEVER directly compare selected academic year with
     * Student.admissionYear.
     *
     * Example:
     * admissionYear = "2026"
     * academicYear = "2025-2026"
     */
    fun normalizeYear(value: String): String {
        val text = value.trim()
        val match = Regex("^(\\d{4})\\s*[-/]\\s*(\\d{2,4})$").matchEntire(text)
        if (match != null) {
            val start = match.groupValues[1]
            val rawEnd = match.groupValues[2]
            return "$start-${rawEnd.takeLast(2)}"
        }
        val start = text.toIntOrNull() ?: return ""
        return "$start-${((start + 1) % 100).toString().padStart(2, '0')}"
    }

    // API/view data may contain either 2025, 2025-26 or 2025-2026.
    // Normalize both sides to the same canonical YYYY-YY representation.
    return normalizeYear(student.admissionYear) == normalizeYear(selectedAcademicYear)
}


// =====================================================
// BRANCH FILTER
// =====================================================

private fun matchesBranch(
    student: Student,
    selectedBranch: String
): Boolean {

    if (selectedBranch == ALL_BRANCHES) {
        return true
    }

    val canonicalStudentBranch =
        BranchCatalog.canonicalBranch(
            student.branch
        )

    return canonicalStudentBranch == selectedBranch
}


// =====================================================
// CATEGORY FILTER
// =====================================================

private fun matchesCategory(
    student: Student,
    selectedCategory: String
): Boolean {

    if (selectedCategory == ALL_CATEGORIES) {
        return true
    }

    return getReportCategory(student) == selectedCategory
}


